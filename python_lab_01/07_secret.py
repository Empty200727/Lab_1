"""Задание 07: расшифровка сообщения срезами.

Ключ (номера букв, а не индексы):
  1 слово - 4-я буква;
  2 слово - буквы 10..13;
  3 слово - буквы 6..15 через одну;
  4 слово - буквы 8..13 в обратном порядке;
  5 слово - буквы 17..21 в обратном порядке.
"""

secret_message = [
    'квевтфпп6щ3стмзалтнмаршгб5длгуча',
    'дьсеы6лц2бане4т64ь4б3ущея6втщл6б',
    'т3пплвце1н3и2кд4лы12чф1ап3бкычаь',
    'ьд5фму3ежородт9г686буиимыкучшсал',
    'бсц59мегщ2лятьаьгенедыв9фк9ехб1а',
]

# Для каждой строки сообщения - свой срез.
# Номер буквы n соответствует индексу n - 1.
KEY = (
    slice(3, 4),
    slice(9, 13),
    slice(5, 15, 2),
    slice(12, 6, -1),
    slice(20, 15, -1),
)


def decode(lines, key=KEY):
    """Применяет к каждой строке свой срез и склеивает слова через пробел."""
    words = [line[part] for line, part in zip(lines, key)]
    return ' '.join(words)


def run():
    print(decode(secret_message))


if __name__ == '__main__':
    run()
