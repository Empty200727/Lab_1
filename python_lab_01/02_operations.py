#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Задание 02: расстановка знаков между числами 1 2 3 4 5.

Разрешены только +, -, * и скобки, порядок чисел менять нельзя.
Требуется получить значение 25. Для образца дан пример (1 + 2) * 3 = 9.
"""


def sample_expression():
    """Образец из условия для чисел 1 2 3."""
    return (1 + 2) * 3


def target_expression():
    """Выражение для чисел 1 2 3 4 5, равное 25."""
    return ((1 + 2) * 3 - 4) * 5


def run():
    print(f'(1 + 2) * 3 = {sample_expression()}')
    print(f'((1 + 2) * 3 - 4) * 5 = {target_expression()}')


if __name__ == '__main__':
    run()
